export const depthFor = (d: Difficulty) => scale(d, [1, 2, 3, 3])

export interface Puzzle { board: Board; moves: number; rules: MateRules; allChecks: boolean; source: string; mirrored: boolean }

export function puzzleFor(configId: string, d: Difficulty, seed: number): Puzzle {
  const cfg = CONFIGS[configId] ?? CONFIGS['ju-zhong-mi']
  const id = CONFIGS[configId] ? configId : 'ju-zhong-mi'
  const n = depthFor(d)
  const set = PUZZLES[id]
  // D3 draws from the lighter half of the mate-in-3 set, D4 from the heavier.
  let pool = set[n]
  if (n === 3) {
    const sorted = [...pool].sort((a, b) => a.split(' ').length - b.split(' ').length || (a < b ? -1 : 1))
    const half = Math.ceil(sorted.length / 2)
    pool = d === 3 ? sorted.slice(0, half) : sorted.slice(sorted.length - half)
  }
  const h = (seed >>> 0)
  const source = pool[h % pool.length]
  const mirrored = Math.floor(h / pool.length) % 2 === 1
  return { board: parse(source, mirrored), moves: n, rules: { variant: cfg.variant, mateBy: cfg.mateBy }, allChecks: cfg.allChecks, source, mirrored }
}

/** Moves red may make: all legal moves, or only checks under the seven-stars rule. */
export function redMoves(p: Pick<Puzzle, 'rules' | 'allChecks'>, b: Board): Move[] {
  const ms = legalMoves(b, 1, p.rules.variant)
  return p.allChecks ? ms.filter(m => givesCheck(b, m, 1, p.rules.variant)) : ms
}

export type TurnResult = { board: Board; reply: Move | null; afterReply: Board | null; result: 'win' | 'lose' | null; why: string }

/** Play red's move (with `left` red moves remaining, counting this one) and black's answer. */
export function playTurn(p: Puzzle, b: Board, m: Move, left: number, seed: number): TurnResult {
  const v = p.rules.variant
  const mine = applyMove(b, m)
  const blackMoves = legalMoves(mine, -1, v)
  if (!blackMoves.length) {
    if (isMate(mine, 1, p.rules)) return { board: mine, reply: null, afterReply: null, result: 'win', why: 'mate' }
    if (v === 'xiangqi') return { board: mine, reply: null, afterReply: null, result: 'lose', why: 'wrong-piece' }
    // Janggi: black cannot move but is not in check — it passes.
    if (left <= 1) return { board: mine, reply: null, afterReply: mine, result: 'lose', why: 'moves' }
    return { board: mine, reply: null, afterReply: mine, result: null, why: 'pass' }
  }
  if (left <= 1) return { board: mine, reply: null, afterReply: null, result: 'lose', why: 'moves' }
  const reply = defend(mine, left - 1, p.rules, seed)!
  const after = applyMove(mine, reply)
  if (!redMoves(p, after).length) return { board: mine, reply, afterReply: after, result: 'lose', why: p.allChecks && legalMoves(after, 1, v).length ? 'no-check' : 'stuck' }
  return { board: mine, reply, afterReply: after, result: null, why: '' }
}

