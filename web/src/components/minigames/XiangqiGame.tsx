// Xiangqi Mates — Chinese chess mating puzzles on the full 9×10 board.  You
// play red and must checkmate black within the move count; black answers
// every move with its best defence, found by a minimax search.
//
// Full rules: the river (elephants stay home, soldiers turn sideways once
// across), the palace (general and advisors stay inside), the horse's leg
// and the elephant's eye block them, the cannon captures over exactly one
// screen, and the two generals may never face each other on an open file
// (the "flying general").  A side with no legal move loses, in check or not.
//
// Each config is a different rule or theme:
//   ju-zhong-mi  classic composed endgames in the spirit of the Ming manual
//   cannon       the final, mating check must come from a cannon
//   horse        the final, mating check must come from a horse
//   seven-stars  composed-endgame rule: red must give check on EVERY move —
//                black's own attack is one move from mating you
//   janggi       Korean rules: no river, palace diagonals, elephants step 1+2,
//                cannons must jump a screen even to move and never jump or take
//                a cannon, soldiers step sideways from the start, no flying
//                general; a side with no move but not in check passes
//
//   D1  mate in 1      D2  mate in 2      D3  mate in 3      D4  mate in 3,
//   from the larger, busier positions
//
// Puzzles come from a set generated by the exported engine and verified by
// the tests: red forces mate in exactly N with checks; at most two first
// moves work; at least one other checking move fails (and loses, because the
// defender then holds out past the move count).  The seed picks a puzzle and
// may mirror it left–right.

export type Variant = 'xiangqi' | 'janggi'
export const K = 1, A = 2, E = 3, H = 4, R = 5, C = 6, P = 7
export type Board = Int8Array
export interface Move { from: number; to: number }

