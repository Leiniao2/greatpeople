// ── Board ─────────────────────────────────────────────────────────────────────

export const sq = (x: number, y: number) => y * 9 + x
export const fx = (i: number) => i % 9
export const fy = (i: number) => Math.floor(i / 9)
const onBoard = (x: number, y: number) => x >= 0 && x < 9 && y >= 0 && y < 10
export const inPalace = (x: number, y: number, side: number) => x >= 3 && x <= 5 && (side > 0 ? y <= 2 : y >= 7)
const anyPalace = (x: number, y: number) => inPalace(x, y, 1) || inPalace(x, y, -1)
/** Palace points on a diagonal line: the corners and the centre. */
const onDiag = (x: number, y: number) => anyPalace(x, y) && (x === 4 ? y === 1 || y === 8 : y === 0 || y === 2 || y === 7 || y === 9)
const palaceCentreY = (y: number) => (y <= 2 ? 1 : 8)

const LETTERS = 'KAEHRCP'
/** Parse "Ke0 Rd7 ke9" (upper case red, lower case black; file a–i, rank 0–9). */
export function parse(s: string, mirror = false): Board {
  const b = new Int8Array(90)
  for (const tok of s.trim().split(/\s+/)) {
    if (!tok) continue
    const t = LETTERS.indexOf(tok[0].toUpperCase()) + 1
    const x = tok.charCodeAt(1) - 97, y = Number(tok[2])
    b[sq(mirror ? 8 - x : x, y)] = tok[0] === tok[0].toUpperCase() ? t : -t
  }
  return b
}
export function format(b: Board): string {
  const out: string[] = []
  for (let i = 0; i < 90; i++) if (b[i]) {
    const l = LETTERS[Math.abs(b[i]) - 1]
    out.push(`${b[i] > 0 ? l : l.toLowerCase()}${String.fromCharCode(97 + fx(i))}${fy(i)}`)
  }
  return out.join(' ')
}

export function kingOf(b: Board, side: number): number {
  for (let i = 0; i < 90; i++) if (b[i] === K * side) return i
  return -1
}

/** Moves of one piece, ignoring whether its own general is left in check. */
export function pieceMoves(b: Board, from: number, v: Variant, out: Move[] = []): Move[] {
  const p = b[from]
  if (!p) return out
  const side = p > 0 ? 1 : -1, t = Math.abs(p)
  const x = fx(from), y = fy(from)
  const add = (nx: number, ny: number) => {
    if (!onBoard(nx, ny)) return
    const q = b[sq(nx, ny)]
    if (q * side > 0) return
    out.push({ from, to: sq(nx, ny) })
  }
  const ORTH = [[1, 0], [-1, 0], [0, 1], [0, -1]]
  const DIAG = [[1, 1], [1, -1], [-1, 1], [-1, -1]]
  /** Palace-diagonal steps from (x, y): only along the drawn lines. */
  const diagSteps = () => {
    if (!onDiag(x, y)) return [] as number[][]
    const cy = palaceCentreY(y)
    if (x === 4 && y === cy) return DIAG
    return [[Math.sign(4 - x), Math.sign(cy - y)]]
  }
  switch (t) {
    case K: case A: {
      if (v === 'xiangqi') {
        for (const [dx, dy] of t === K ? ORTH : DIAG) if (inPalace(x + dx, y + dy, side)) add(x + dx, y + dy)
      } else {
        for (const [dx, dy] of ORTH) if (inPalace(x + dx, y + dy, side)) add(x + dx, y + dy)
        for (const [dx, dy] of diagSteps()) if (inPalace(x + dx, y + dy, side)) add(x + dx, y + dy)
      }
      break
    }
    case E: {
      if (v === 'xiangqi') {
        for (const [dx, dy] of DIAG) {
          const nx = x + 2 * dx, ny = y + 2 * dy
          if (!onBoard(nx, ny) || (side > 0 ? ny > 4 : ny < 5)) continue
          if (b[sq(x + dx, y + dy)]) continue // the elephant's eye
          add(nx, ny)
        }
      } else {
        for (const [dx, dy] of ORTH) {
          if (!onBoard(x + dx, y + dy) || b[sq(x + dx, y + dy)]) continue
          for (const s of [-1, 1]) {
            const ex = dx || s, ey = dy || s
            const mx = x + dx + ex, my = y + dy + ey
            if (!onBoard(mx, my) || b[sq(mx, my)]) continue
            add(mx + ex, my + ey)
          }
        }
      }
      break
    }
    case H: {
      for (const [dx, dy] of ORTH) {
        if (!onBoard(x + dx, y + dy) || b[sq(x + dx, y + dy)]) continue // the horse's leg
        for (const s of [-1, 1]) add(x + 2 * dx + (dx ? 0 : s), y + 2 * dy + (dy ? 0 : s))
      }
      break
    }
    case R: {
      const rays = [...ORTH.map(d => ({ d, palace: false })), ...diagSteps().map(d => ({ d, palace: true }))]
      for (const { d: [dx, dy], palace } of v === 'janggi' ? rays : rays.filter(r => !r.palace)) {
        let nx = x + dx, ny = y + dy
        while (onBoard(nx, ny) && (!palace || anyPalace(nx, ny))) {
          const q = b[sq(nx, ny)]
          if (q) { if (q * side < 0) out.push({ from, to: sq(nx, ny) }); break }
          out.push({ from, to: sq(nx, ny) })
          if (palace && !onDiag(nx, ny)) break
          nx += dx; ny += dy
        }
      }
      break
    }
    case C: {
      const rays = [...ORTH.map(d => ({ d, palace: false })), ...(v === 'janggi' ? diagSteps().map(d => ({ d, palace: true })) : [])]
      for (const { d: [dx, dy], palace } of rays) {
        let nx = x + dx, ny = y + dy
        let screen = false
        while (onBoard(nx, ny) && (!palace || anyPalace(nx, ny))) {
          const q = b[sq(nx, ny)]
          if (!screen) {
            if (q) {
              if (v === 'janggi' && Math.abs(q) === C) break // a cannon never jumps a cannon
              screen = true
            } else if (v === 'xiangqi') out.push({ from, to: sq(nx, ny) })
          } else if (q) {
            if (q * side < 0 && !(v === 'janggi' && Math.abs(q) === C)) out.push({ from, to: sq(nx, ny) })
            break
          } else if (v === 'janggi') out.push({ from, to: sq(nx, ny) })
          nx += dx; ny += dy
        }
      }
      break
    }
    case P: {
      const fwd = side
      add(x, y + fwd)
      const crossed = v === 'janggi' || (side > 0 ? y >= 5 : y <= 4)
      if (crossed) { add(x - 1, y); add(x + 1, y) }
      if (v === 'janggi' && inPalace(x, y, -side) && onDiag(x, y)) {
        const cy = palaceCentreY(y)
        for (const [dx, dy] of DIAG) {
          if (dy !== fwd) continue
          const nx = x + dx, ny = y + dy
          if (!inPalace(nx, ny, -side)) continue
          // Along a drawn diagonal only: to or from the centre.
          if ((x === 4 && y === cy) || (nx === 4 && ny === cy)) add(nx, ny)
        }
      }
      break
    }
  }
  return out
}

export function pseudoMoves(b: Board, side: number, v: Variant): Move[] {
  const out: Move[] = []
  for (let i = 0; i < 90; i++) if (b[i] * side > 0) pieceMoves(b, i, v, out)
  return out
}

export function applyMove(b: Board, m: Move): Board {
  const n = new Int8Array(b)
  n[m.to] = n[m.from]
  n[m.from] = 0
  return n
}

/** The two generals on one file with nothing between them. */
export function generalsFace(b: Board): boolean {
  const r = kingOf(b, 1), k = kingOf(b, -1)
  if (r < 0 || k < 0 || fx(r) !== fx(k)) return false
  for (let y = fy(r) + 1; y < fy(k); y++) if (b[sq(fx(r), y)]) return false
  return true
}

/** Squares of the pieces giving check to `side`'s general (the facing general counts in xiangqi). */
export function checkers(b: Board, side: number, v: Variant): number[] {
  const k = kingOf(b, side)
  if (k < 0) return []
  const out: number[] = []
  const tmp: Move[] = []
  for (let i = 0; i < 90; i++) if (b[i] * side < 0) {
    tmp.length = 0
    pieceMoves(b, i, v, tmp)
    if (tmp.some(m => m.to === k)) out.push(i)
  }
  if (v === 'xiangqi' && generalsFace(b)) out.push(kingOf(b, -side))
  return out
}

export function inCheck(b: Board, side: number, v: Variant): boolean {
  return checkers(b, side, v).length > 0
}

export function legalMoves(b: Board, side: number, v: Variant): Move[] {
  return pseudoMoves(b, side, v).filter(m => {
    if (Math.abs(b[m.to]) === K) return true // taking the general (only arises off-puzzle)
    return !inCheck(applyMove(b, m), side, v)
  })
}

export interface MateRules { variant: Variant; mateBy: number | null }

/** After a move by `att`, is the other side lost (checkmated, or in xiangqi stalemated), by the config's rule? */
export function isMate(b: Board, att: number, r: MateRules): boolean {
  if (legalMoves(b, -att, r.variant).length) return false
  const chk = checkers(b, -att, r.variant)
  if (!chk.length && r.variant === 'janggi') return false // no move but not in check: pass
  if (r.mateBy) return chk.some(i => Math.abs(b[i]) === r.mateBy)
  return true
}

export const givesCheck = (b: Board, m: Move, att: number, v: Variant) => inCheck(applyMove(b, m), -att, v)

/**
 * Can `att` (to move) force mate within n of its own moves, giving check every
 * move?  A sound proof of a forced mate; the defender tries every legal reply.
 */
export function mateIn(b: Board, att: number, n: number, r: MateRules): boolean {
  if (n <= 0) return false
  for (const m of legalMoves(b, att, r.variant)) {
    const b2 = applyMove(b, m)
    if (!inCheck(b2, -att, r.variant)) continue
    const replies = legalMoves(b2, -att, r.variant)
    if (!replies.length) { if (isMate(b2, att, r)) return true; continue }
    if (n === 1) continue
    let all = true
    for (const rep of replies) if (!mateIn(applyMove(b2, rep), att, n - 1, r)) { all = false; break }
    if (all) return true
  }
  return false
}

/** The shortest forced mate (checks only) up to `max`, or Infinity. */
export function mateDistance(b: Board, att: number, max: number, r: MateRules): number {
  for (let n = 1; n <= max; n++) if (mateIn(b, att, n, r)) return n
  return Infinity
}

/** First moves that force mate within n. */
export function winningMoves(b: Board, att: number, n: number, r: MateRules): Move[] {
  return legalMoves(b, att, r.variant).filter(m => {
    const b2 = applyMove(b, m)
    if (!inCheck(b2, -att, r.variant)) return false
    const replies = legalMoves(b2, -att, r.variant)
    if (!replies.length) return isMate(b2, att, r)
    return n > 1 && replies.every(rep => mateIn(applyMove(b2, rep), att, n - 1, r))
  })
}

/**
 * Black's reply: the move after which red's forced mate is furthest away (or
 * gone) within the red moves left.  Ties go to captures, then to the seed.
 */
export function defend(b: Board, redMovesLeft: number, r: MateRules, seed: number): Move | null {
  const replies = legalMoves(b, -1, r.variant)
  if (!replies.length) return null
  let best: Move | null = null, bestKey = -Infinity
  for (const m of replies) {
    const d = mateDistance(applyMove(b, m), 1, redMovesLeft, r)
    const tie = (b[m.to] ? 0.5 : 0) + (hashString(`${seed}:${m.from}-${m.to}`) % 1000) / 4000
    const key = (d === Infinity ? 100 : d) + tie
    if (key > bestKey) { bestKey = key; best = m }
  }
  return best
}

