// Cells are [row, col] with row 0 at the bottom.  `k` is the face colour
// (only used by opus reticulatum: 0 light, 1 dark).

export interface Cell { r: number; c: number; k: number }
export interface Stone { shape: string; cells: Cell[] }

export const SHAPES: Record<string, [number, number][]> = {
  mono: [[0, 0]],
  dom: [[0, 0], [0, 1]],
  i3: [[0, 0], [0, 1], [0, 2]],
  i4: [[0, 0], [0, 1], [0, 2], [0, 3]],
  o: [[0, 0], [0, 1], [1, 0], [1, 1]],
  r23: [[0, 0], [0, 1], [0, 2], [1, 0], [1, 1], [1, 2]],
  l3: [[0, 0], [0, 1], [1, 0]],
  t: [[0, 0], [0, 1], [0, 2], [1, 1]],
  s: [[0, 0], [0, 1], [1, 1], [1, 2]],
  z: [[1, 0], [1, 1], [0, 1], [0, 2]],
  l: [[0, 0], [0, 1], [0, 2], [1, 0]],
  j: [[0, 0], [0, 1], [0, 2], [1, 2]],
  p5: [[0, 0], [0, 1], [1, 0], [1, 1], [2, 0]],
}

const WEIGHT = [0, 0.12, 0.5, 1, 1.5, 1.2, 0.9]

export function normalize(cells: Cell[]): Cell[] {
  const mr = Math.min(...cells.map(x => x.r)), mc = Math.min(...cells.map(x => x.c))
  return cells.map(x => ({ r: x.r - mr, c: x.c - mc, k: x.k })).sort((a, b) => a.r - b.r || a.c - b.c)
}

/** Quarter-turn `times` times (normalised). */
export function rotate(cells: Cell[], times: number): Cell[] {
  let cur = cells
  for (let i = 0; i < ((times % 4) + 4) % 4; i++) cur = cur.map(x => ({ r: -x.c, c: x.r, k: x.k }))
  return normalize(cur)
}

export const widthOf = (cells: Cell[]) => Math.max(...cells.map(x => x.c)) + 1
export const heightOf = (cells: Cell[]) => Math.max(...cells.map(x => x.r)) + 1

// ── Board and rules ────────────────────────────────────────────────────────────

export const EMPTY = 0, STONE = 1, ROCK = 2

export interface Site {
  W: number
  H: number
  /** Gate cells: must stay empty, never count as gaps. */
  gate: boolean[]
  /** Formwork: max height difference between columns, or null. */
  spread: number | null
  checker: boolean
}

export interface WallState {
  grid: number[]
  /** Face colour of each placed cell (-1 none). */
  face: number[]
  /** Which stone (sequence index) fills each cell, -1 none. */
  owner: number[]
  next: number
  rejectsUsed: number
  gaps: number
  mismatches: number
}

export function columnHeights(site: Site, grid: number[]): number[] {
  const hs: number[] = []
  for (let c = 0; c < site.W; c++) {
    let h = 0
    for (let r = site.H - 1; r >= 0; r--) if (grid[r * site.W + c] !== EMPTY) { h = r + 1; break }
    hs.push(h)
  }
  return hs
}

export function countGaps(site: Site, grid: number[]): number {
  const hs = columnHeights(site, grid)
  let n = 0
  for (let c = 0; c < site.W; c++) for (let r = 0; r < hs[c]; r++) {
    const i = r * site.W + c
    if (grid[i] === EMPTY && !site.gate[i]) n++
  }
  return n
}

export interface Landing {
  /** Board indices the stone would occupy (may include rows ≥ H when too high). */
  cells: { r: number; c: number; k: number }[]
  y: number
  legal: boolean
  reason?: 'too-high' | 'gate' | 'formwork'
}

/** Where `cells` lands when dropped with its left edge at `col`; null when off the board. */
export function land(site: Site, grid: number[], cells: Cell[], col: number): Landing | null {
  if (col < 0 || col + widthOf(cells) > site.W) return null
  const hs = columnHeights(site, grid)
  let y = 0
  for (const x of cells) y = Math.max(y, hs[col + x.c] - x.r)
  const placed = cells.map(x => ({ r: y + x.r, c: col + x.c, k: x.k }))
  if (placed.some(p => p.r >= site.H)) return { cells: placed, y, legal: false, reason: 'too-high' }
  if (placed.some(p => site.gate[p.r * site.W + p.c])) return { cells: placed, y, legal: false, reason: 'gate' }
  if (site.spread !== null) {
    const nh = [...hs]
    for (const p of placed) nh[p.c] = Math.max(nh[p.c], p.r + 1)
    if (Math.max(...nh) - Math.min(...nh) > site.spread) return { cells: placed, y, legal: false, reason: 'formwork' }
  }
  return { cells: placed, y, legal: true }
}

export function netColour(r: number, c: number) { return (r + c) % 2 }

function placeOnto(site: Site, s: WallState, l: Landing, owner: number): WallState {
  const grid = [...s.grid], face = [...s.face], own = [...s.owner]
  let mismatches = s.mismatches
  for (const p of l.cells) {
    const i = p.r * site.W + p.c
    grid[i] = STONE; face[i] = p.k; own[i] = owner
    if (site.checker && p.k !== netColour(p.r, p.c)) mismatches++
  }
  return { ...s, grid, face, owner: own, mismatches, gaps: countGaps(site, grid) }
}

export interface Plan {
  configId: string
  rule: Rule
  site: Site
  difficulty: Difficulty
  start: WallState
  sequence: Stone[]
  /** Known winning moves for the first `solution.length` stones. */
  solution: { rot: number; col: number }[]
  spares: number
  preview: number
  rejects: number
  maxFlaws: number
}

export function stoneCells(plan: Plan, s: WallState, rot: number): Cell[] | null {
  const st = plan.sequence[s.next]
  return st ? rotate(st.cells, rot) : null
}

/** Drop the current stone. Returns null for an illegal or impossible drop. */
export function applyMove(plan: Plan, s: WallState, rot: number, col: number): WallState | null {
  const cells = stoneCells(plan, s, rot)
  if (!cells) return null
  const l = land(plan.site, s.grid, cells, col)
  if (!l || !l.legal) return null
  return { ...placeOnto(plan.site, s, l, s.next), next: s.next + 1 }
}

/** Send the current stone back to the quarry. */
export function rejectStone(plan: Plan, s: WallState): WallState | null {
  if (s.rejectsUsed >= plan.rejects || s.next >= plan.sequence.length) return null
  return { ...s, next: s.next + 1, rejectsUsed: s.rejectsUsed + 1 }
}

export function legalMoves(plan: Plan, s: WallState): { rot: number; col: number }[] {
  const out: { rot: number; col: number }[] = []
  if (s.next >= plan.sequence.length) return out
  for (let rot = 0; rot < 4; rot++) {
    const cells = stoneCells(plan, s, rot)!
    for (let col = 0; col + widthOf(cells) <= plan.site.W; col++) {
      const l = land(plan.site, s.grid, cells, col)
      if (l && l.legal) out.push({ rot, col })
    }
  }
  return out
}

export const flawsOf = (s: WallState) => s.gaps + s.mismatches

export function isComplete(plan: Plan, s: WallState): boolean {
  return columnHeights(plan.site, s.grid).every(h => h === plan.site.H)
}

export type Status = { kind: 'playing' } | { kind: 'won' } | { kind: 'lost'; reason: string }

export function statusOf(plan: Plan, s: WallState): Status {
  if (flawsOf(s) > plan.maxFlaws) return { kind: 'lost', reason: plan.site.checker ? 'Too many flaws in the facing' : 'Too many gaps in the wall' }
  if (isComplete(plan, s)) return { kind: 'won' }
  if (s.next >= plan.sequence.length) return { kind: 'lost', reason: 'The quarry has run out of stones' }
  if (!legalMoves(plan, s).length && s.rejectsUsed >= plan.rejects) return { kind: 'lost', reason: 'This stone fits nowhere on the wall' }
  return { kind: 'playing' }
}

// ── Generation ─────────────────────────────────────────────────────────────────

export const DIMS: Record<Difficulty, { W: number; H: number }> = {
  1: { W: 6, H: 4 }, 2: { W: 7, H: 5 }, 3: { W: 7, H: 6 }, 4: { W: 8, H: 6 },
}
/** Max stones the builder may use, so a level stays short. */
export const STONE_BUDGET: Record<Difficulty, number> = { 1: 9, 2: 12, 3: 14, 4: 16 }

function emptyState(site: Site): WallState {
  const n = site.W * site.H
  return { grid: Array(n).fill(EMPTY), face: Array(n).fill(-1), owner: Array(n).fill(-1), next: 0, rejectsUsed: 0, gaps: 0, mismatches: 0 }
}

function makeSite(rule: Rule, d: Difficulty, rng: Rng): { site: Site; start: WallState } {
  const { W, H } = DIMS[d]
  const site: Site = { W, H, gate: Array(W * H).fill(false), spread: rule === 'formwork' ? scale(d, [3, 2, 2, 2]) : null, checker: rule === 'checker' }
  const start = emptyState(site)
  if (rule === 'gates') {
    const count = scale(d, [1, 1, 2, 2])
    const widths = scale<number[]>(d, [[1], [2], [1, 1], [2, 1]])
    for (let tries = 0; tries < 200; tries++) {
      const taken: [number, number][] = []
      let ok = true
      for (let g = 0; g < count && ok; g++) {
        const w = widths[g]
        const x = randInt(rng, 1, W - 1 - w)
        if (taken.some(([a, b]) => x < b + 2 && a < x + w + 2)) ok = false
        else taken.push([x, x + w])
      }
      if (!ok) continue
      for (const [a, b] of taken) for (let c = a; c < b; c++) for (let r = 0; r < 2; r++) site.gate[r * W + c] = true
      break
    }
  }
  if (rule === 'bedrock') {
    const max = scale(d, [1, 2, 2, 2])
    let hs: number[] = []
    do hs = Array.from({ length: W }, () => randInt(rng, 0, max))
    while (hs.every(h => h === hs[0]))
    hs.forEach((h, c) => { for (let r = 0; r < h; r++) start.grid[r * W + c] = ROCK })
  }
  return { site, start }
}

interface Built { sequence: Stone[]; solution: { rot: number; col: number }[] }

/** Greedy gap-free builder; null when it paints itself into a corner. */
function build(site: Site, start: WallState, shapes: string[], budget: number, rng: Rng): Built | null {
  let s = start
  const sequence: Stone[] = [], solution: { rot: number; col: number }[] = []
  while (!columnHeights(site, s.grid).every(h => h === site.H)) {
    if (sequence.length >= budget) return null
    const order = shapes
      .map(id => ({ id, key: Math.pow(rng(), 1 / WEIGHT[SHAPES[id].length]) }))
      .sort((a, b) => b.key - a.key)
    let chosen: { cells: Cell[]; l: Landing; col: number } | null = null
    for (const { id } of order) {
      const base: Cell[] = SHAPES[id].map(([r, c]) => ({ r, c, k: 0 }))
      let best: { cells: Cell[]; l: Landing; col: number; score: number } | null = null
      for (let rot = 0; rot < 4; rot++) {
        const cells = rotate(base, rot)
        for (let col = 0; col + widthOf(cells) <= site.W; col++) {
          const l = land(site, s.grid, cells, col)
          if (!l || !l.legal) continue
          const trial = placeOnto(site, s, l, 0)
          if (trial.gaps > 0) continue
          const score = l.y + rng() * 0.9
          if (!best || score < best.score) best = { cells, l, col, score }
        }
      }
      if (best) { chosen = best; break }
    }
    if (!chosen) return null
    // Faces take the colour of the net where the stone is set.
    const placed = chosen.l.cells.map(p => ({ ...p, k: site.checker ? netColour(p.r, p.c) : 0 }))
    const finalCells = normalize(placed.map(p => ({ r: p.r - chosen!.l.y, c: p.c - chosen!.col, k: p.k })))
    const q = randInt(rng, 0, 3)
    sequence.push({ shape: SHAPES_KEY(chosen.cells), cells: rotate(finalCells, q) })
    solution.push({ rot: (4 - q) % 4, col: chosen.col })
    s = { ...placeOnto(site, s, { ...chosen.l, cells: placed }, 0), next: 0 }
  }
  return { sequence, solution }
}

function SHAPES_KEY(cells: Cell[]): string {
  for (const id of Object.keys(SHAPES)) {
    const base: Cell[] = SHAPES[id].map(([r, c]) => ({ r, c, k: 0 }))
    if (base.length !== cells.length) continue
    for (let rot = 0; rot < 4; rot++) {
      const a = rotate(base, rot)
      if (a.every((x, i) => x.r === cells[i].r && x.c === cells[i].c)) return id
    }
  }
  return 'stone'
}

export function planWall(configId: string, difficulty: Difficulty, seed: number): Plan {
  const id = CONFIGS[configId] ? configId : 'great-wall'
  const cfg = CONFIGS[id]
  const base = hashString(`wallbuilder:${id}:${difficulty}:${seed}`)
  for (let attempt = 0; ; attempt++) {
    const rng = mulberry32(base + attempt * 7919)
    const { site, start } = makeSite(cfg.rule, difficulty, rng)
    const built = build(site, start, cfg.shapes, STONE_BUDGET[difficulty], rng)
    if (!built && attempt < 400) continue
    if (!built) throw new Error('wallbuilder: no buildable wall')
    const spares = scale(difficulty, [2, 2, 2, 2])
    const sequence = [...built.sequence]
    for (let i = 0; i < spares; i++) {
      const shp = cfg.shapes[Math.floor(rng() * cfg.shapes.length)]
      const phase = randInt(rng, 0, 1)
      const cells = normalize(SHAPES[shp].map(([r, c]) => ({ r, c, k: site.checker ? (r + c + phase) % 2 : 0 })))
      sequence.push({ shape: shp, cells: rotate(cells, randInt(rng, 0, 3)) })
    }
    return {
      configId: id, rule: cfg.rule, site, difficulty, start, sequence, solution: built.solution, spares,
      preview: scale(difficulty, [3, 2, 2, 2]),
      rejects: scale(difficulty, [3, 2, 2, 2]),
      maxFlaws: cfg.flaws[difficulty - 1],
    }
  }
}

// ── Component ──────────────────────────────────────────────────────────────────

function centreCol(plan: Plan, s: WallState, rot: number): number {
  const cells = stoneCells(plan, s, rot)
  return cells ? Math.floor((plan.site.W - widthOf(cells)) / 2) : 0
}

export default function WallBuilderGame({ configId, difficulty, seed, params, onWin, onLose }: MinigameProps) {
  const cfg = resolveConfig(CONFIGS, configId, params, 'great-wall')
  const plan = useMemo(() => planWall(configId, difficulty, seed), [configId, difficulty, seed])
  const { site } = plan
  const [state, setState] = useState<WallState>(plan.start)
  const [aim, setAim] = useState({ rot: 0, col: centreCol(plan, plan.start, 0) })
  const { outcome, reason, settled, win, lose } = useGameOutcome({ onWin, onLose })

  useEffect(() => {
    setState(plan.start)
    setAim({ rot: 0, col: centreCol(plan, plan.start, 0) })
  }, [plan])

  const cells = stoneCells(plan, state, aim.rot)
  const landing = cells ? land(site, state.grid, cells, aim.col) : null

  const settle = useCallback((next: WallState) => {
    const st = statusOf(plan, next)
    if (st.kind === 'won') win()
    else if (st.kind === 'lost') lose(st.reason)
  }, [plan, win, lose])

  const shift = useCallback((dc: number) => {
    if (settled) return
    setAim(a => {
      const c = stoneCells(plan, state, a.rot)
      return c ? { ...a, col: Math.max(0, Math.min(site.W - widthOf(c), a.col + dc)) } : a
    })
  }, [settled, plan, state, site.W])

  const turn = useCallback(() => {
    if (settled) return
    setAim(a => {
      const rot = (a.rot + 1) % 4
      const c = stoneCells(plan, state, rot)
      if (!c) return a
      return { rot, col: Math.max(0, Math.min(site.W - widthOf(c), a.col)) }
    })
  }, [settled, plan, state, site.W])

  const drop = useCallback(() => {
    if (settled) return
    const next = applyMove(plan, state, aim.rot, aim.col)
    if (!next) return
    setState(next)
    setAim({ rot: 0, col: centreCol(plan, next, 0) })
    settle(next)
  }, [settled, plan, state, aim, settle])

  const reject = useCallback(() => {
    if (settled) return
    const next = rejectStone(plan, state)
    if (!next) return
    setState(next)
    setAim({ rot: 0, col: centreCol(plan, next, 0) })
    settle(next)
  }, [settled, plan, state, settle])

  const tapColumn = (c: number) => {
    if (settled || !cells) return
    const w = widthOf(cells)
    setAim(a => ({ ...a, col: Math.max(0, Math.min(site.W - w, c - Math.floor((w - 1) / 2))) }))
  }

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      const t = e.target as HTMLElement | null
      if (t && (t.tagName === 'INPUT' || t.tagName === 'TEXTAREA')) return
      if (e.key === 'ArrowLeft' || e.key === 'a' || e.key === 'A') { e.preventDefault(); shift(-1) }
      else if (e.key === 'ArrowRight' || e.key === 'd' || e.key === 'D') { e.preventDefault(); shift(1) }
      else if (e.key === 'ArrowUp' || e.key === 'w' || e.key === 'W' || e.key === 'r' || e.key === 'R') { e.preventDefault(); turn() }
      else if (e.key === 'ArrowDown' || e.key === ' ' || e.key === 'Enter' || e.key === 's' || e.key === 'S') { e.preventDefault(); drop() }
      else if (e.key === 'x' || e.key === 'X') { e.preventDefault(); reject() }
    }
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [shift, turn, drop, reject])

  const ghost = new Map<number, number>()
  if (landing && !settled) for (const p of landing.cells) if (p.r < site.H) ghost.set(p.r * site.W + p.c, p.k)
  const legal = !!landing?.legal
  const stonesLeft = plan.sequence.length - state.next
  const flaws = flawsOf(state)
  const upcoming = plan.sequence.slice(state.next + 1, state.next + 1 + plan.preview)
  const why = landing && !landing.legal
    ? landing.reason === 'too-high' ? 'Too high — the stone would stick out above the line'
      : landing.reason === 'gate' ? 'That would block a gateway'
        : `Formwork: no column may stand more than ${site.spread} above the lowest`
    : ''
  const rows = Array.from({ length: site.H }, (_, i) => site.H - 1 - i)

  const fill = (i: number, k: number) => {
    if (site.checker) return k === 1 ? cfg.stones[1] : cfg.stones[0]
    return cfg.stones[state.owner[i] % cfg.stones.length]
  }

  return (
    <div className="flex flex-col gap-3 bg-paper-2 rounded-xl p-3 sm:p-4">
      <div className="flex items-start justify-between gap-3">
        <div>
          <p className="text-accent text-[10px] font-bold uppercase tracking-widest">{cfg.title}</p>
          <p className="text-muted text-xs leading-relaxed">{cfg.intro}</p>
        </div>
        <div className="shrink-0 text-right text-[10px] text-muted tabular-nums">
          <p className="font-bold text-ink-2" data-testid="wall-stones">Stones {stonesLeft}</p>
          <p className={flaws >= plan.maxFlaws ? 'text-red-600 font-bold' : ''} data-testid="wall-flaws">
            {site.checker ? 'Flaws' : 'Gaps'} {flaws} / {plan.maxFlaws}
          </p>
          <p data-testid="wall-rejects">Rejects {plan.rejects - state.rejectsUsed}</p>
        </div>
      </div>

      <div className="flex items-end gap-2 justify-center">
        <div className="flex flex-col items-center gap-1">
          <span className="text-[9px] uppercase tracking-widest text-accent font-bold">Now</span>
          {cells ? <MiniStone cells={cells} checker={site.checker} cfg={cfg} big /> : <span className="text-muted text-xs">—</span>}
        </div>
        {upcoming.map((st, i) => (
          <div key={state.next + 1 + i} className="flex flex-col items-center gap-1 opacity-70" data-testid="wall-preview">
            <span className="text-[9px] uppercase tracking-widest text-muted">Next{i ? ` ${i + 1}` : ''}</span>
            <MiniStone cells={st.cells} checker={site.checker} cfg={cfg} />
          </div>
        ))}
      </div>

      <div className="w-full max-w-[360px] mx-auto select-none rounded-lg overflow-hidden border-2 border-ink-2 bg-paper shadow-md"
        style={{ touchAction: 'manipulation' }} data-testid="wall-board">
        <div className="grid" style={{ gridTemplateColumns: `repeat(${site.W}, 1fr)` }}>
          {rows.map(r => Array.from({ length: site.W }, (_, c) => {
            const i = r * site.W + c
            const g = state.grid[i]
            const gate = site.gate[i]
            const gh = ghost.get(i)
            const mismatch = site.checker && g === STONE && state.face[i] !== netColour(r, c)
            const top = r === site.H - 1
            const bg = g === ROCK ? 'bg-[#6b6259]'
              : g === STONE ? fill(i, state.face[i])
                : gate ? 'bg-[#3c3a36]'
                  : site.checker ? (netColour(r, c) ? 'bg-[#7a5a3c]/15' : 'bg-paper')
                    : 'bg-paper'
            return (
              <button key={i} type="button" tabIndex={-1} onClick={() => tapColumn(c)} data-cell={i}
                aria-label={g === ROCK ? 'bedrock' : g === STONE ? 'stone' : gate ? 'gateway' : 'empty'}
                className={`relative aspect-square border border-line/40 ${bg} ${top ? 'border-t-2 border-t-accent' : ''}`}>
                {gate && g === EMPTY && <span className="absolute inset-x-[15%] top-[10%] bottom-0 rounded-t-full bg-[#1f1d1a]" />}
                {g === STONE && <span className="absolute inset-[6%] rounded-[2px] border border-black/20" />}
                {mismatch && <span className="absolute inset-[18%] rounded-full ring-2 ring-red-500/80" />}
                {gh !== undefined && g === EMPTY && (
                  <span className={`absolute inset-[8%] rounded-[2px] border-2 border-dashed
                    ${legal ? 'border-emerald-600' : 'border-red-500'}
                    ${site.checker ? (gh ? 'bg-[#7a5a3c]/60' : 'bg-[#efe3c4]/80') : legal ? 'bg-emerald-500/20' : 'bg-red-500/20'}`} />
                )}
              </button>
            )
          }))}
        </div>
      </div>

      <p className="text-[10px] text-center min-h-[14px] text-red-600 font-bold">{!settled ? why : ''}</p>

      {!settled && (
        <div className="flex items-center gap-1.5 w-full max-w-[360px] mx-auto">
          <CtrlButton label="left" onClick={() => shift(-1)}>◀</CtrlButton>
          <CtrlButton label="rotate" onClick={turn}>⟳</CtrlButton>
          <CtrlButton label="right" onClick={() => shift(1)}>▶</CtrlButton>
          <button type="button" onClick={drop} disabled={!legal} data-testid="wall-drop"
            className="flex-[2] h-11 rounded-lg bg-accent text-accent-fg text-xs font-bold disabled:opacity-40">▼ Drop</button>
          <button type="button" onClick={reject} disabled={state.rejectsUsed >= plan.rejects} data-testid="wall-reject"
            className="flex-1 h-11 rounded-lg border bg-panel border-line text-ink-2 text-[11px] font-bold disabled:opacity-40">✕ Reject</button>
        </div>
      )}
      <p className="text-muted/80 text-[10px] text-center">
        {settled ? '' : 'Tap a column or ◀ ▶ to aim · ⟳ / ↑ rotate · Drop / ↓ / Space · X rejects a stone'}
      </p>

      <OutcomeBanner outcome={outcome} detail={cfg.fact} winTitle="The wall stands level!"
        loseTitle={reason ?? 'The wall is unfinished'} />
    </div>
  )
}

function MiniStone({ cells, checker, cfg, big }: { cells: Cell[]; checker: boolean; cfg: WallConfig; big?: boolean }) {
  const w = widthOf(cells), h = heightOf(cells)
  const size = big ? 14 : 10
  return (
    <div className="grid gap-px p-1 rounded bg-panel border border-line"
      style={{ gridTemplateColumns: `repeat(${w}, ${size}px)`, gridAutoRows: `${size}px` }}>
      {Array.from({ length: h }, (_, i) => h - 1 - i).map(r => Array.from({ length: w }, (_, c) => {
        const cell = cells.find(x => x.r === r && x.c === c)
        return <span key={`${r}:${c}`} className={cell ? `${checker ? cfg.stones[cell.k] : cfg.stones[0]} rounded-[1px] border border-black/20` : ''} />
      }))}
    </div>
  )
}

function CtrlButton({ label, onClick, children }: { label: string; onClick: () => void; children: React.ReactNode }) {
  return (
    <button type="button" aria-label={label} onClick={onClick}
      className="flex-1 h-11 rounded-lg border bg-panel border-line text-ink font-bold active:bg-accent/20">{children}</button>
  )
}
