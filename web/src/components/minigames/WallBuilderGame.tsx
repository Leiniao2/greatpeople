// Wall Builder — a turn-based falling-block wall.  Each stone is shown in
// turn (with a preview of the next ones); the player picks its rotation and
// column and lets it drop straight down onto the wall.  Nothing ever clears:
// the wall must rise to the line with every column level, and every empty
// cell left under a stone is a gap.  Too many gaps, no stones left, or a
// stone that fits nowhere (with no rejects left) loses.
//
// Variants change the rules, not just the size:
//   great-wall        rectangular rammed-earth blocks; formwork rule — no
//                     column may rise more than `spread` rows above the lowest
//   inca-ashlar       uneven bedrock and irregular stones (S/Z/T/L/P shapes)
//   hadrian           milecastle gateways must stay open: a stone may never
//                     drop into a gate, so gates are spanned by lintels
//   opus-reticulatum  stones are pre-cut light/dark; cells that miss the
//                     chequered net count as flaws, like gaps
//
//   D1  6×4 wall, see 3 ahead, ≈ 6–9 stones     ~1 min
//   D2  7×5 wall, see 2 ahead, ≈ 8–12 stones    ~1.5 min
//   D3  7×6 wall, see 2 ahead, ≈ 9–14 stones    ~2–2.5 min
//   D4  8×6 wall, see 2 ahead, ≈ 11–16 stones   ~2.5–3 min
//
// Spare stones 2 at every tier; rejects 3 / 2 / 2 / 2.
//
// The stone sequence is generated by building the wall: a seeded greedy
// builder drops stones without leaving a gap until the wall is complete, and
// the order it used becomes the sequence (each stone handed over in a random
// rotation), plus a spare or two at the end.  The builder's moves are a
// known solution, which the tests replay through the rules.

export type Rule = 'formwork' | 'bedrock' | 'gates' | 'checker'

