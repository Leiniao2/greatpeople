// Pictures for the Archive Pairs slips, one per tile text.  People who are
// Great People cards reuse their card portrait (`card`); everything else is
// painted in Google Flow from `subject`.  Originals live in
// data/images/pairs/<key>.jpeg and scripts/build-images.mjs writes
// web/public/pairs/<key>.webp.

export interface SlipArt { key: string; subject?: string; card?: string }

/** "Sun Tzu" → "sun_tzu", "Earth's girth" → "earths_girth". */
export const slipKey = (text: string) =>
  text.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/['’.]/g, '').replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '')

const p = (text: string, subject: string): [string, SlipArt] => [text, { key: slipKey(text), subject }]
const c = (text: string, card: string): [string, SlipArt] => [text, { key: slipKey(text), card }]

